#include "libft.h"

void	*ft_calloc(size_t nmemb, size_t size)
{
	size_t	max;
	void	*ptr;

	max = (size_t)(-1);
	if (nmemb != 0 && size > max / nmemb)
		return (NULL);
	ptr = malloc(nmemb * size);
	if (ptr == NULL)
		return (NULL);
	ft_bzero(ptr, nmemb * size);
	return (ptr);
}
